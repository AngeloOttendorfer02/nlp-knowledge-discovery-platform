def parse_token_column(value):
    """
    Convert a token column loaded from CSV into a Python list.

    Supports:
    - actual Python lists
    - string representations of lists
    - whitespace-separated strings
    - NaN values
    """
    if pd.isna(value):
        return []

    if isinstance(value, list):
        return value

    if isinstance(value, str):
        try:
            parsed = ast.literal_eval(value)

            if isinstance(parsed, list):
                return parsed

        except (ValueError, SyntaxError):
            return value.split()

    return []