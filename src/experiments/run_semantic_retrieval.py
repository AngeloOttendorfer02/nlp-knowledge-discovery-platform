"""Run the reproducible embedding-based semantic retrieval experiment."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Sequence

import yaml

from src.experiments.common import (
    evaluate_rankings,
    load_documents,
    load_evaluation_queries,
    normalize_top_ks,
    validate_relevance_against_corpus,
    write_experiment_outputs,
)
from src.retrieval.embedding_retriever import EmbeddingRetriever


def run_semantic_experiment(
    *,
    documents_path: str | Path,
    queries_path: str | Path,
    output_dir: str | Path = "reports/tables",
    model_name: str = "all-MiniLM-L6-v2",
    batch_size: int = 32,
    top_ks: Sequence[int] = (5, 10),
    cache_path: str | Path | None = "artifacts/semantic_retrieval/document_embeddings.npz",
    force_recompute: bool = False,
    retriever=None,
):
    """Execute semantic retrieval and save ranked results plus summary metrics."""
    top_ks = normalize_top_ks(top_ks)
    documents = load_documents(documents_path)
    queries = load_evaluation_queries(queries_path)
    validate_relevance_against_corpus(queries, documents["doc_id"])

    doc_ids = documents["doc_id"].astype(str).tolist()
    texts = documents["text"].fillna("").astype(str).tolist()

    semantic_retriever = retriever or EmbeddingRetriever(
        model_name=model_name,
        batch_size=batch_size,
    )
    semantic_retriever.index(
        doc_ids,
        texts,
        cache_path=cache_path,
        force_recompute=force_recompute,
    )

    retrieval_depth = max(top_ks)
    rankings = {
        query.query_id: semantic_retriever.search(query.query, top_k=retrieval_depth)
        for query in queries
    }

    results, metrics = evaluate_rankings(
        method="semantic",
        queries=queries,
        rankings=rankings,
        top_ks=top_ks,
    )
    result_path, metric_path = write_experiment_outputs(
        results,
        metrics,
        output_dir=output_dir,
        result_filename="semantic_results.csv",
        metric_filename="semantic_metrics.csv",
    )

    return results, metrics, result_path, metric_path


def _config_defaults(config_path: str | Path) -> tuple[str, int, int]:
    path = Path(config_path)
    if not path.exists():
        return "all-MiniLM-L6-v2", 32, 10

    with path.open("r", encoding="utf-8") as handle:
        config = yaml.safe_load(handle) or {}

    retrieval = config.get("retrieval", {})
    embeddings = config.get("embeddings", {})
    model_name = retrieval.get(
        "embedding_model",
        embeddings.get("model", "all-MiniLM-L6-v2"),
    )
    batch_size = embeddings.get("batch_size", 32)
    top_k = retrieval.get("top_k", 10)
    return str(model_name), int(batch_size), int(top_k)


def parse_args() -> argparse.Namespace:
    default_model, default_batch_size, default_top_k = _config_defaults("config.yaml")

    parser = argparse.ArgumentParser(
        description="Evaluate Sentence-Transformer semantic retrieval."
    )
    parser.add_argument(
        "--documents",
        default="data/processed/processed_documents.csv",
        help="Processed document CSV generated by the pipeline.",
    )
    parser.add_argument(
        "--queries",
        default="data/evaluation/retrieval_queries.example.json",
        help="Evaluation JSON containing query and relevant_doc_ids entries.",
    )
    parser.add_argument("--output-dir", default="reports/tables")
    parser.add_argument("--model", default=default_model)
    parser.add_argument("--batch-size", type=int, default=default_batch_size)
    parser.add_argument(
        "--top-k",
        type=int,
        nargs="+",
        default=sorted({5, default_top_k}),
        help="One or more cutoffs, for example: --top-k 5 10",
    )
    parser.add_argument(
        "--cache-path",
        default="artifacts/semantic_retrieval/document_embeddings.npz",
    )
    parser.add_argument(
        "--force-recompute",
        action="store_true",
        help="Ignore a valid embedding cache.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    _, metrics, result_path, metric_path = run_semantic_experiment(
        documents_path=args.documents,
        queries_path=args.queries,
        output_dir=args.output_dir,
        model_name=args.model,
        batch_size=args.batch_size,
        top_ks=args.top_k,
        cache_path=args.cache_path,
        force_recompute=args.force_recompute,
    )

    print(f"Semantic ranked results: {result_path}")
    print(f"Semantic summary metrics: {metric_path}")
    print(metrics.to_string(index=False))


if __name__ == "__main__":
    main()
